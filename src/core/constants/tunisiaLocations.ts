/** Find which governorate a municipality belongs to */
export function findGovernorateForMunicipality(municipality: string): string | null {
  const lower = municipality.toLowerCase();
  for (const gov of TUNISIA_GOVERNORATES) {
    if (gov.municipalities.some((m) => m.toLowerCase() === lower)) {
      return gov.name;
    }
  }
  return null;
}

/** Get all municipalities for a given governorate name */
export function getMunicipalitiesForGovernorate(governorate: string): string[] {
  const gov = TUNISIA_GOVERNORATES.find(
    (g) => g.name.toLowerCase() === governorate.toLowerCase(),
  );
  return gov?.municipalities ?? [];
}

/** All municipalities across all governorates, sorted A→Z */
export const ALL_MUNICIPALITIES: { name: string; governorate: string }[] = TUNISIA_GOVERNORATES.flatMap(
  (gov) => gov.municipalities.map((m) => ({ name: m, governorate: gov.name })),
).sort((a, b) => a.name.localeCompare(b.name));

export interface LocationSearchResult {
  type: 'governorate' | 'municipality';
  value: string;
  governorate: string;
}

/** Search across all governorates and municipalities */
export function searchTunisiaLocations(query: string): LocationSearchResult[] {
  if (!query.trim()) return [];
  const q = query.toLowerCase();
  const results: LocationSearchResult[] = [];

  for (const gov of TUNISIA_GOVERNORATES) {
    if (gov.name.toLowerCase().includes(q)) {
      results.push({ type: 'governorate', value: gov.name, governorate: gov.name });
    }
    for (const mun of gov.municipalities) {
      if (mun.toLowerCase().includes(q)) {
        results.push({ type: 'municipality', value: mun, governorate: gov.name });
      }
    }
  }

  return results;
}
