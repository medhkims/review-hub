async function seedDeliveryCompanies() {
  console.log('=== Seeding Delivery Companies (corrected — no fake data) ===\n');

  for (const biz of DELIVERY_BUSINESSES) {
    const { id, ...data } = biz;
    await db.collection('businesses').doc(id).set({
      ...data,
      created_at: admin.firestore.FieldValue.serverTimestamp(),
      updated_at: admin.firestore.FieldValue.serverTimestamp(),
    });
    console.log(`  + ${biz.name} — ${biz.location}`);
  }

  console.log(`\nSeeded ${DELIVERY_BUSINESSES.length} delivery companies.`);
}

seedDeliveryCompanies()
  .then(() => {
    console.log('\nDone!');
    process.exit(0);
  })
  .catch((err) => {
    console.error('Seed failed:', err);
    process.exit(1);
  });
